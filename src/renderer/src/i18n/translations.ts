export type TranslationKey = keyof typeof english

export function translate(
  language: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const localized = (
    translations as Partial<Record<Language, Partial<Record<TranslationKey, string>>>>
  )[language]
  let text: string = localized?.[key] ?? translations.en[key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, () => String(v))
    }
  }
  return text
}
